use reqwest::StatusCode;
#[cfg(not(feature = "alias"))]
use reqwest::header::CONTENT_TYPE;

#[cfg(feature = "alias")]
use bitwarden_alias::{
    Alias, AliasClient, AliasClientSettings, AliasError, CreateRandomAliasRequest,
};
#[cfg(feature = "alias")]
use bitwarden_sensitive_value::{ExposeSensitive, SensitiveString};

use crate::username::UsernameError;

pub(crate) async fn generate(
    http: &reqwest::Client,
    api_key: String,
    base_url: String,
    website: Option<String>,
) -> Result<String, UsernameError> {
    #[cfg(feature = "alias")]
    {
        let _ = http;
        let settings =
            AliasClientSettings::new(SensitiveString::from(api_key)).with_base_url(base_url);
        let website = website.map(SensitiveString::from);
        generate_alias(settings, website)
            .await
            .map(|alias| alias.email.expose_owned())
            .map_err(map_alias_error)
    }

    #[cfg(not(feature = "alias"))]
    {
        generate_with_api_url(http, api_key, base_url, website).await
    }
}

#[cfg(feature = "alias")]
pub(crate) async fn generate_alias(
    settings: AliasClientSettings,
    website: Option<SensitiveString>,
) -> Result<Alias, AliasError> {
    let note =
        super::format_description(&website.as_ref().map(|website| website.expose().to_owned()));
    AliasClient::new(settings)?
        .create_random_alias(CreateRandomAliasRequest {
            hostname: website,
            mode: None,
            note: Some(SensitiveString::from(note)),
        })
        .await
}

#[cfg(feature = "alias")]
fn map_alias_error(error: AliasError) -> UsernameError {
    match error {
        AliasError::AuthenticationFailed | AliasError::InvalidAuthenticationToken => {
            UsernameError::InvalidApiKey
        }
        AliasError::Provider { status } => match StatusCode::from_u16(status) {
            Ok(status) => UsernameError::ResponseContent {
                status,
                message: "request failed".to_owned(),
            },
            Err(_) => UsernameError::Unknown,
        },
        AliasError::Transport(error) => UsernameError::Reqwest(error),
        AliasError::InvalidRequest(_)
        | AliasError::InvalidBaseUrl(_)
        | AliasError::InvalidConnectionIdentity
        | AliasError::RedirectRejected { .. }
        | AliasError::MutationOutcomeUnknown { .. }
        | AliasError::MutationCommittedButRefreshFailed { .. }
        | AliasError::MutationResponseInvalid { .. }
        | AliasError::ConcurrentMutation { .. }
        | AliasError::RateLimited { .. }
        | AliasError::ResponseTooLarge { .. }
        | AliasError::UnexpectedContentType
        | AliasError::InvalidResponse(_)
        | AliasError::InvalidResponseValue(_) => UsernameError::Unknown,
    }
}

#[cfg(not(feature = "alias"))]
async fn generate_with_api_url(
    http: &reqwest::Client,
    api_key: String,
    api_url: String,
    website: Option<String>,
) -> Result<String, UsernameError> {
    let query = website
        .as_ref()
        .map(|w| format!("?hostname={w}"))
        .unwrap_or_default();

    let note = super::format_description(&website);

    #[derive(serde::Serialize)]
    struct Request {
        note: String,
    }

    let response = http
        .post(format!("{api_url}/api/alias/random/new{query}"))
        .header(CONTENT_TYPE, "application/json")
        .header("Authentication", api_key)
        .json(&Request { note })
        .send()
        .await?;

    if response.status() == StatusCode::UNAUTHORIZED {
        return Err(UsernameError::InvalidApiKey);
    }

    // Throw any other errors
    response.error_for_status_ref()?;

    #[derive(serde::Deserialize)]
    struct Response {
        alias: String,
    }
    let response: Response = response.json().await?;

    Ok(response.alias)
}

