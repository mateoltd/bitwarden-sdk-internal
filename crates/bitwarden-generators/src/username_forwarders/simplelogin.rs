    #[cfg(feature = "alias")]
    #[tokio::test]
    async fn forwarded_username_generation_uses_alias_core_and_returns_only_address() {
        use bitwarden_api_base::new_http_client;
        use wiremock::{Mock, ResponseTemplate, matchers};

        let server = wiremock::MockServer::start().await;
        server
            .register(
                Mock::given(matchers::path("/api/alias/random/new"))
                    .and(matchers::method("POST"))
                    .and(matchers::query_param("hostname", "example.com"))
                    .and(matchers::header("Authentication", "MY_TOKEN"))
                    .and(matchers::body_json(json!({
                        "note": "Website: example.com. Generated by Bitwarden."
                    })))
                    .respond_with(
                        ResponseTemplate::new(201)
                            .set_body_json(alias_json(418, "simplelogin.yut3g8@aleeas.com")),
                    )
                    .expect(1),
            )
            .await;
        server
            .register(
                Mock::given(matchers::path("/api/alias/random/new"))
                    .and(matchers::method("POST"))
                    .and(matchers::query_param("hostname", "example.com"))
                    .and(matchers::header("Authentication", "MY_FAKE_TOKEN"))
                    .and(matchers::body_json(json!({
                        "note": "Website: example.com. Generated by Bitwarden."
                    })))
                    .respond_with(ResponseTemplate::new(401).set_body_json(json!({
                        "error": "invalid token MY_FAKE_TOKEN"
                    })))
                    .expect(1),
            )
            .await;

        let address = super::generate(
            &new_http_client(),
            "MY_TOKEN".into(),
            server.uri(),
            Some("example.com".into()),
        )
        .await
        .expect("forwarded-username generation should succeed through alias-core");
        assert_eq!(address, "simplelogin.yut3g8@aleeas.com");

        let fake_token_error = super::generate(
            &new_http_client(),
            "MY_FAKE_TOKEN".into(),
            server.uri(),
            Some("example.com".into()),
        )
        .await
        .expect_err("invalid authentication should retain the public error variant");
        assert_eq!(
            fake_token_error.to_string(),
            UsernameError::InvalidApiKey.to_string()
        );
        assert!(!fake_token_error.to_string().contains("MY_FAKE_TOKEN"));

        server.verify().await;
    }

    #[cfg(feature = "alias")]
    #[tokio::test]
    async fn delegated_generation_respects_sensitive_debug_mode_and_strips_transport_urls() {
        use bitwarden_alias::AliasClientSettings;
        use bitwarden_sensitive_value::SensitiveString;

        const TOKEN: &str = "token-that-must-not-render";
        const HOSTNAME: &str = "hostname-that-must-not-render.example";

        let settings = AliasClientSettings::new(SensitiveString::from(TOKEN));
        let hostname = SensitiveString::from(HOSTNAME);
        assert_eq!(
            format!("{settings:?}").contains(TOKEN),
            format!("{:?}", SensitiveString::from(TOKEN)).contains(TOKEN)
        );
        assert_eq!(
            format!("{hostname:?}").contains(HOSTNAME),
            format!("{:?}", SensitiveString::from(HOSTNAME)).contains(HOSTNAME)
        );

        let server = wiremock::MockServer::start().await;
        let private_base_url = format!("{}/private-provider-path", server.uri());
        drop(server);

        let error = super::generate(
            &bitwarden_api_base::new_http_client(),
            TOKEN.to_owned(),
            private_base_url,
            Some(HOSTNAME.to_owned()),
        )
        .await
        .expect_err("a stopped provider should return a transport error");
        let rendered = error.to_string();
        assert!(!rendered.contains(TOKEN));
        assert!(!rendered.contains(HOSTNAME));
        assert!(!rendered.contains("private-provider-path"));
    }

